/* ---------- glosses: the chapter's 5 words, tappable wherever they appear in the target text ---------- */
function glossForms(word){
  var out = [], add = function(x){ x = String(x || '').trim(); if(x && out.indexOf(x) < 0) out.push(x); };
  var w = String(word || '').trim(), m = /^(.*?)o\/-a$/.exec(w);
  if(m) ['o', 'a', 'os', 'as'].forEach(function(s){ add(m[1] + s); }); else add(w);
  out.slice().forEach(function(x){ var a = /^(el|la|los|las|un|una|the|a|an)\s+(.+)$/i.exec(x); if(a) add(a[2]); });
  out.slice().forEach(function(x){ if(!/\s/.test(x) && !/s$/i.test(x) && !/^\d+$/.test(x)) add(x + 's'); });
  return out.sort(function(a, b){ return b.length - a.length; });
}
function glossList(ch){
  var list = [];
  Object.keys(ch.glosses || {}).forEach(function(g){
    var gl = ch.glosses[g], src = glossForms(gl.word).concat(gl.forms || []).map(reEsc);
    list.push({g:g, src:src, re:new RegExp('^(?:' + src.join('|') + ')$', 'iu')});
  });
  return list;
}
function glossHtml(text, ch, feelG){
  var s = String(text || ''), list = glossList(ch);
  var alts = [].concat.apply([], list.map(function(x){ return x.src; })).sort(function(a, b){ return b.length - a.length; });
  if(!alts.length) return esc(s);
  var re = new RegExp('(^|[^\\p{L}\\p{N}])(' + alts.join('|') + ')(?![\\p{L}\\p{N}])', 'giu');
  var out = '', last = 0, m;
  while((m = re.exec(s))){
    var start = m.index + m[1].length, word = m[2], hit = null;
    for(var i = 0; i < list.length; i++) if(list[i].re.test(word)){ hit = list[i]; break; }
    out += esc(s.slice(last, start)) + '<button type="button" class="yc-gl' + (hit && hit.g === feelG ? ' yc-feelw' : '') + '" data-g="' + (hit ? hit.g : '') + '">' + esc(word) + '</button>';
    last = start + word.length;
  }
  return out + esc(s.slice(last));
}

