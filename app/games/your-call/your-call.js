function tickThumb(url){
  return new Promise(function(ok){
    var im = new Image();
    im.onload = function(){
      try{
        var w = 150, h = Math.round(150 * im.height / im.width), c = D.createElement('canvas'); c.width = w; c.height = h;
        var x = c.getContext('2d'); x.drawImage(im, 0, 0, w, h);
        x.strokeStyle = '#C8352B'; x.lineWidth = 7; x.lineCap = 'round'; x.lineJoin = 'round';
        x.beginPath(); x.moveTo(w * .62, h * .2); x.lineTo(w * .72, h * .32); x.lineTo(w * .9, h * .08); x.stroke();
        ok(c.toDataURL('image/webp', .8));
      }catch(e){ ok(url); }
    };
    im.onerror = function(){ ok(url); };
    im.src = url;
  });
}
var SHARED = null;   // the poster's bed, adopted by the next YourCall.start
function hush(){ LIVE_SOUNDS.slice().forEach(function(x){ try{ x.close(); }catch(e){} }); SHARED = null; }
function posterSound(muted){
  hush();
  var t0 = Date.now();
  SHARED = Sound(muted, {alive:function(){ return !!(W.Theatre && W.Theatre.isOpen && W.Theatre.isOpen()) || Date.now() - t0 < 4000; }});
  SHARED.bed('S1', {});
}
function poster(content, path, o){
  o = o || {};
  if(typeof o.muted === 'function') try{ posterSound(o.muted); }catch(e){}
  var C = content, base = o.base || '', ui = o.ui || 'en', chs = (path && path.choices) || [];
  var card = o.card || [1, 2];
  var src = function(id){ var a = C.art.items[id]; return a && a.src ? base + C.art.base + a.src : null; };
  // chapter flow (UI0ejg05): in a step only its first unplayed chapter can be opened; the other one waits "After chapter {n}"
  // (before, photo 2 could be tapped first and chapter 1 was skipped for good)
  var firstOpen = card.filter(function(n){ return !chs[n]; })[0];
  var items = C.chapters.map(function(c){
    var played = !!chs[c.n], inCard = card.indexOf(c.n) >= 0;
    var pic = postcardArt(c, chs);
    var st = played ? 'developed' : (inCard && c.n === firstOpen ? 'developing' : 'locked');
    // GDD 4: a grey chapter says where it opens (ch1-2 = the level's .1 page, ch3-6 = the .2 page)
    var note = st === 'locked' ? (inCard ? fmt(UI.afterCh[ui] || UI.afterCh.en, {n:firstOpen})
      : (UI.opensOn[ui] || UI.opensOn.en).replace('{p}', (C.level || 'A1') + (c.n <= 2 ? '.1' : '.2'))) : '';
    return {id:'ch' + c.n, label:String(c.n), thumb:played ? src(pic) : null, state:st, note:note, n:c.n,
      onTap:function(it){ if(o.onChapter) o.onChapter(it.n, {replay:it.state === 'developed' && !inCard}); }};
  });
  return Promise.all(items.map(function(it){ return it.state === 'developed' && it.thumb ? tickThumb(it.thumb).then(function(u){ it.thumb = u; }) : null; })).then(function(){
    return {
      poster:{title:C.title, tagline:C.tagline, art:C.cover ? src(C.cover) : null, artReady:!!(C.cover && src(C.cover)),
        palette:{sky:'#F6F0E2', sky2:'#E9E1CE', glow:'#FFF3D0', ground:'#7FB7D8', ink:'#1B1A17', accent:'#C8352B', accentInk:'#ffffff'}},
      strip:items, stage:'4:5',
      controls:[{id:'album', label:UI.album, icon:ICON.album, onTap:function(){ if(o.onAlbum) o.onAlbum(); }}]
    };
  });
}

