  async function runChapter(n, resume){
    var ch = C.chapters[n - 1];
    if(!ch) throw new Error('no chapter ' + n);
    G.ch = ch; G.ended = false;
    preload(ch);
    G.run = resume && resume.ch === n ? resume : {v:1, ch:n, i:0, picks:['', ''], tn:null, note:null, startedAt:Date.now()};
    page.innerHTML = '';
    page.classList.toggle('yc-devch', !!ch.auto || !ready(C, [n]));
    snd.dim(1); chapterScene(ch, G.run.i || 0);
    if(!resume){
      G.wait = 'title';
      var title = us('chapter', {n:n}), sub = tg(ch.title);
      if(o.theatre && o.theatre.titleCard) await o.theatre.titleCard(title, sub, {ms:1500 * Math.max(pace, .2)});
      else await ownTitle(title, sub);
      if(!G.alive) return;
      var first = cards[0] === n && mode !== 'replay' && (n === 3 || n === 5);
      if(first) await previously(n === 3 ? 2 : 3);
    }
    save();
    var startI = G.run.i;
    for(var i = 0; i < ch.seq.length; i++){
      if(!G.alive) return;
      var instant = i < startI;
      if(!instant){ G.run.i = i; save(); }
      await playBeat(ch.seq[i], ch, instant);
      if(!G.alive) return;
    }
    G.run.i = ch.seq.length;
    var result = {level:C.level, ch:n, picks:G.run.picks.join(''), found:((G.run.tn && G.run.tn.found) || []).filter(function(x){ return x[0] !== '#'; }),
      note:G.run.note ? G.run.note.text : null, noteChoice:G.run.note ? G.run.note.pick : null,
      souvenir:souvenirOf(ch), endings:n === 6 ? endings(C, arcChoices()) : null, ms:Date.now() - (G.run.startedAt || Date.now())};
    if(mode !== 'replay'){ try{ host.commit && host.commit(result); }catch(e){ console.warn('[your-call] commit', e); } }
    if(o.onChapterDone) try{ o.onChapterDone(result); }catch(e){}
    var r = await postcard(ch, n === 6);
    if(!G.alive) return;
    if(r.next){ G.run = null; save(); return runChapter(r.next, null); }
    G.run = null; if(mode !== 'replay' && host.saveRun) try{ host.saveRun(null); }catch(e){}
    G.ended = true;
    snd.close(true);
    if(r.later){ if(o.onPause) o.onPause(result); return; }
    if(o.onCardDone) o.onCardDone(result);
  }
