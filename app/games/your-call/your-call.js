  function distTo(f, x, y, ratioHW){
    // distance in "% of width" units from (x,y) (plate %) to the nearest box of a change
    var best = 1e9;
    boxesOf(f).forEach(function(b){
      var dx = Math.max(b.x - x, 0, x - (b.x + b.w)), dy = Math.max(b.y - y, 0, y - (b.y + b.h)) * ratioHW;
      best = Math.min(best, Math.sqrt(dx * dx + dy * dy));
    });
    return best;
  }
